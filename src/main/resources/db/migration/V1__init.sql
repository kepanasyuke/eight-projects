-- Схема восьми проектов. Одна и та же миграция применяется к H2 (MODE=PostgreSQL) и к PostgreSQL.

create table assignee (
    id         bigint generated by default as identity primary key,
    name       varchar(80)  not null,
    email      varchar(160) not null,
    created_at timestamp    not null,
    constraint uq_assignee_email unique (email)
);

create table work_item (
    id          bigint generated by default as identity primary key,
    title       varchar(120)  not null,
    description varchar(2000),
    status      varchar(20)   not null,
    priority    integer       not null,
    assignee_id bigint,
    version     bigint        not null default 0,
    created_at  timestamp     not null,
    updated_at  timestamp     not null,
    constraint fk_work_item_assignee foreign key (assignee_id) references assignee (id),
    constraint ck_work_item_status check (status in ('NEW', 'IN_PROGRESS', 'BLOCKED', 'DONE', 'CANCELLED')),
    constraint ck_work_item_priority check (priority between 1 and 5)
);

create table work_note (
    id           bigint generated by default as identity primary key,
    work_item_id bigint        not null,
    author       varchar(80)   not null,
    content      varchar(1000) not null,
    created_at   timestamp     not null,
    constraint fk_work_note_item foreign key (work_item_id) references work_item (id) on delete cascade
);

create table idempotency_record (
    id              bigint generated by default as identity primary key,
    idempotency_key varchar(120) not null,
    operation       varchar(120) not null,
    response_body   varchar(4000) not null,
    status_code     integer      not null,
    created_at      timestamp    not null,
    constraint uq_idempotency_key unique (idempotency_key),
    constraint ck_idempotency_status check (status_code between 100 and 599)
);

create table audit_record (
    id         bigint generated by default as identity primary key,
    kind       varchar(40)  not null,
    message    varchar(400) not null,
    created_at timestamp    not null
);

create table ledger_account (
    id      bigint generated by default as identity primary key,
    code    varchar(40)    not null,
    balance numeric(18, 2) not null,
    version bigint         not null default 0,
    constraint uq_ledger_account_code unique (code),
    constraint ck_ledger_balance check (balance >= 0)
);

create table ledger_entry (
    id             bigint generated by default as identity primary key,
    source_account varchar(40)    not null,
    target_account varchar(40)    not null,
    amount         numeric(18, 2) not null,
    operation      varchar(20)    not null,
    created_at     timestamp      not null,
    constraint ck_ledger_entry_amount check (amount > 0)
);

create table outbox_message (
    id         bigint generated by default as identity primary key,
    topic      varchar(60)   not null,
    payload    varchar(4000) not null,
    status     varchar(20)   not null,
    attempts   integer       not null default 0,
    created_at timestamp     not null,
    sent_at    timestamp,
    constraint ck_outbox_status check (status in ('PENDING', 'SENT')),
    constraint ck_outbox_attempts check (attempts >= 0)
);

create table game_score (
    id         bigint generated by default as identity primary key,
    player     varchar(40) not null,
    level      integer     not null,
    score      integer     not null,
    seconds    integer     not null,
    created_at timestamp   not null,
    constraint ck_game_score_level check (level between 1 and 8),
    constraint ck_game_score_score check (score >= 0),
    constraint ck_game_score_seconds check (seconds >= 0)
);

create index idx_work_item_status on work_item (status);
create index idx_work_item_assignee on work_item (assignee_id);
create index idx_work_item_priority on work_item (status, priority, id);
create index idx_work_note_item on work_note (work_item_id);
create index idx_audit_record_created on audit_record (created_at);
create index idx_ledger_entry_created on ledger_entry (created_at);
create index idx_outbox_pending on outbox_message (status, id);
create index idx_game_score_rank on game_score (score desc, seconds asc);
